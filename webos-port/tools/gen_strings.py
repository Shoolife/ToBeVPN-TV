#!/usr/bin/env python3
"""Builds app/strings.js from the Android TV string resources, so the webOS
port shows exactly the same wording in both languages."""
import json, os, re, xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, '..', 'app', 'src', 'main', 'res')

def text_of(el):
    raw = ''.join(el.itertext())
    if raw.startswith('"') and raw.endswith('"'):
        raw = raw[1:-1]
    raw = raw.replace("\\'", "'").replace('\\"', '"').replace('\\n', '\n').replace('\\@', '@').replace('\\?', '?')
    return raw

def load(path):
    out = {}
    root = ET.parse(path).getroot()
    for el in root:
        name = el.get('name')
        if el.tag == 'string':
            out[name] = text_of(el)
        elif el.tag == 'plurals':
            out[name] = {item.get('quantity'): text_of(item) for item in el}
    return out

data = {'ru': load(os.path.join(RES, 'values-ru', 'strings.xml')), 'en': load(os.path.join(RES, 'values', 'strings.xml'))}
for key, value in data['en'].items():
    data['ru'].setdefault(key, value)
with open(os.path.join(ROOT, 'app', 'strings.js'), 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/gen_strings.py from the Android TV resources. Do not edit.\n')
    f.write('window.TOBE_STRINGS = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':'), sort_keys=True) + ';\n')
print(len(data['ru']), len(data['en']))
